"""Build the hosted no-account example in docs/try/ (run: npm run build:example).

Bundles the seeded CSVs and the captured Sample AI responses into docs/try/data.js
and writes docs/.nojekyll so GitHub Pages serves every file as-is. The example
computes share, growth gap and status in JavaScript with the same rules as the
Snowflake views (see data/README.md).
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"


def rows(name, numeric):
    with open(ROOT / "app" / "sample" / name) as f:
        out = list(csv.DictReader(f))
    for r in out:
        for k in numeric:
            r[k] = int(r[k])
    return out


data = {
    "categories": rows("categories.csv", []),
    "book": rows("book_monthly.csv", ["processed_volume_usd", "txn_count", "active_merchants"]),
    "market": rows("market_monthly.csv", ["market_sales_usd"]),
    "ai": json.loads((ROOT / "app" / "sample" / "ai.json").read_text()),
}
(DOCS / "try").mkdir(parents=True, exist_ok=True)
(DOCS / "try" / "data.js").write_text("/* Generated by scripts/build_example.py from app/sample/. */\nwindow.MSB = "
                                     + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
(DOCS / ".nojekyll").write_text("")
print("docs/try/data.js written;", len(data["book"]), "book rows,", len(data["ai"]["notes"]), "notes,", len(data["ai"]["ask"]), "answers")
