"""Ask an analyst: questions to the Cortex Agent over the MARKET_SHARE_SV semantic view."""
import pandas as pd
import streamlit as st

import ai
import brand
from views.common import cap


def show_answer(a, mode, animate=False):
    lab = ('<span class="ms-label live">Live · Cortex Agent</span>' if mode == "Live"
           else '<span class="ms-label">Sample AI response</span>')
    st.markdown(f'<p>{lab} <span class="ms-card-s">&nbsp;{a.get("latency_ms", 0) / 1000:.1f} s measured live</span></p>'
                f'<p class="ms-card-h">{brand.esc(a["question"])}</p>', unsafe_allow_html=True)
    ph = st.empty()
    text = a.get("text") or "_The agent returned no text._"
    if animate:
        from views.notes import reveal
        reveal(text, ph)
    else:
        ph.markdown(brand.md_safe(text))
    t = a.get("table")
    if t and t.get("rows"):
        st.markdown('<div class="ms-src">Source: result set from Cortex Analyst over <code>MARKET_SHARE_SV</code></div>', unsafe_allow_html=True)
        st.dataframe(pd.DataFrame(t["rows"], columns=t["columns"]), hide_index=True, use_container_width=True)
    if a.get("sql"):
        with st.expander("SQL generated by Cortex Analyst"):
            st.code(a["sql"], language="sql")


def render(mode):
    st.markdown(brand.header("Ask an analyst", "Ask the benchmark in plain English",
                             "The Market Share Agent uses Cortex Analyst over the MARKET_SHARE_SV semantic view: it writes SQL, runs it and answers from the result.",
                             cap(mode, "Cortex Agent · Cortex Analyst · semantic view"), mode != "Live"), unsafe_allow_html=True)
    samples = ai.sample_ai().get("ask", {})
    with st.container(key="card_ask"):
        st.markdown('<p class="ms-card-s">Suggested questions</p>', unsafe_allow_html=True)
        pick = st.pills("Suggested questions", ai.QUESTIONS, key="a_pick", label_visibility="collapsed")
        q = pick
        if mode == "Live":
            typed = st.chat_input("Ask about share, volume or growth by vertical")
            q = typed or pick
        else:
            st.markdown('<p class="ms-card-s">Sample mode answers the suggested questions with responses captured from Live runs. Switch to Live to ask your own.</p>', unsafe_allow_html=True)
        if q and q != st.session_state.get("a_last_q"):
            st.session_state["a_last_q"] = q
            ph = st.empty()

            def on_step(i, s):
                ph.markdown(f'<div class="ms-card">{brand.steps_html(ai.ASK_STEPS, i)}</div>', unsafe_allow_html=True)
            try:
                if mode == "Live":
                    a = ai.ask_live(q, on_step)
                else:
                    if q not in samples:
                        raise RuntimeError("No captured sample for this question.")
                    ai.sample_wait(on_step, ai.ASK_STEPS)
                    a = samples[q]
            except Exception as e:
                ph.empty()
                st.error(f"Agent call failed: {e}")
                return
            ph.markdown(f'<div class="ms-card">{brand.steps_html(ai.ASK_STEPS, 4, True)}</div>', unsafe_allow_html=True)
            st.session_state["last_answer"] = a
            with st.container(key="card_answer"):
                show_answer(a, mode, True)
        elif st.session_state.get("last_answer"):
            with st.container(key="card_answer"):
                show_answer(st.session_state["last_answer"], mode)
        else:
            st.markdown('<div class="ms-empty"><b>Pick a question</b>The answer shows the SQL Cortex Analyst wrote and the rows it returned.</div>', unsafe_allow_html=True)
