"""Seeded, deterministic generator for the Market Share & Vertical Benchmarking data.

Run:  python3 data/generate.py
Writes the CSVs in data/ and app/sample/ and the generated INSERT block inside
sql/setup.sql (scripts/build_example.py bundles the CSVs for docs/try/). Same seed,
same output, byte for byte. Standard library only.

The drivers and formulas are the original pack's: six MCC-aligned merchant
categories over 24 month-ends (Jul 2024 - Jun 2026), market sales growing
linearly from a base, and the processor's book growing linearly from a base
share. Two changes, both documented in data/README.md:
  * a seasonal factor (holiday lift, January dip) applied equally to the book
    and the market, so share in bps is unaffected;
  * small fixed-seed noise on the book (+/-0.6%) and on active merchants,
    replacing RANDOM() so Sample mode and Snowflake hold the same numbers.
"""
import calendar
import csv
import random
import re
from datetime import date
from pathlib import Path

SEED = 20240731
ROOT = Path(__file__).resolve().parent.parent

# category_code, category_name, mcc, census_variable
CATEGORIES = [
    ("RESTAURANTS", "Restaurants & Food Service", "5812", "ADV_722SM_SA"),
    ("APPAREL", "Clothing & Accessories", "5651", "ADV_448SM_SA"),
    ("ELECTRONICS", "Electronics & Appliances", "5732", "ADV_443SM_SA"),
    ("GROCERY", "Food & Beverage Stores", "5411", "ADV_445SM_SA"),
    ("FURNITURE", "Furniture & Home Furnishings", "5712", "ADV_442SM_SA"),
    ("HEALTH", "Health & Personal Care", "5912", "ADV_446SM_SA"),
]
# base market sales ($M / month), base share of the market, book growth / month, market growth / month
DRIVERS = {
    "RESTAURANTS": (95000, 0.0220, 0.009, 0.004),   # gaining share
    "APPAREL": (26000, 0.0150, 0.002, 0.003),       # holding, slipping slightly
    "ELECTRONICS": (8000, 0.0180, -0.004, 0.002),   # losing share
    "GROCERY": (85000, 0.0120, 0.006, 0.004),       # gaining
    "FURNITURE": (11000, 0.0160, 0.001, 0.000),     # holding
    "HEALTH": (38000, 0.0140, 0.005, 0.003),        # gaining
}
# Month-of-year seasonality, applied to book and market alike.
SEASON = {1: 0.95, 2: 0.96, 3: 1.00, 4: 0.99, 5: 1.01, 6: 1.00,
          7: 1.00, 8: 1.01, 9: 0.98, 10: 1.00, 11: 1.04, 12: 1.09}
MONTHS = 24


def month_ends():
    out, y, m = [], 2024, 7
    for _ in range(MONTHS):
        out.append(date(y, m, calendar.monthrange(y, m)[1]))
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return out


def build():
    rng = random.Random(SEED)
    cats = [{"category_code": c, "category_name": n, "mcc": mcc, "census_variable": v} for c, n, mcc, v in CATEGORIES]
    book, market = [], []
    for code, name, _mcc, _v in CATEGORIES:
        base_mkt, base_share, pg, mg = DRIVERS[code]
        for i, me in enumerate(month_ends()):
            s = SEASON[me.month]
            noise = 1 + rng.randint(-60, 60) / 10000.0
            vol = round(base_mkt * 1e6 * base_share * (1 + pg * i) * s * noise)
            book.append({
                "category_code": code, "month_end": me.isoformat(),
                "processed_volume_usd": vol,
                "txn_count": round(vol / 72.0),
                "active_merchants": 500 + rng.randint(1, 40) + i * 3,
            })
            market.append({"category_code": code, "month_end": me.isoformat(),
                           "market_sales_usd": round(base_mkt * 1e6 * (1 + mg * i) * s)})
    return cats, book, market


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def sql_values(rows, cols):
    def lit(v):
        return f"'{v}'" if isinstance(v, str) else repr(v)
    return ",\n".join("  (" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows)


def sql_block(cats, book, market):
    cc = ["category_code", "category_name", "mcc", "census_variable"]
    bc = ["category_code", "month_end", "processed_volume_usd", "txn_count", "active_merchants"]
    mc = ["category_code", "month_end", "market_sales_usd"]
    return (
        f"-- Generated by data/generate.py (seed {SEED}). Do not edit by hand.\n"
        f"INSERT INTO MARKET_SHARE_MERCHANT_CATEGORY ({', '.join(cc)}) VALUES\n{sql_values(cats, cc)};\n\n"
        f"INSERT INTO MARKET_SHARE_BOOK_RAW ({', '.join(bc)}) VALUES\n{sql_values(book, bc)};\n\n"
        f"INSERT INTO MARKET_SHARE_MARKET_RAW ({', '.join(mc)}) VALUES\n{sql_values(market, mc)};\n"
    )


def main():
    cats, book, market = build()
    for d in (ROOT / "data", ROOT / "app" / "sample"):
        write_csv(d / "categories.csv", cats)
        write_csv(d / "book_monthly.csv", book)
        write_csv(d / "market_monthly.csv", market)
    setup = ROOT / "sql" / "setup.sql"
    if setup.exists():
        s = setup.read_text()
        new = re.sub(r"(-- BEGIN GENERATED DATA\n).*?(-- END GENERATED DATA)",
                     lambda m: m.group(1) + sql_block(cats, book, market) + m.group(2), s, flags=re.S)
        setup.write_text(new)
    print(f"seed {SEED}: {len(cats)} categories, {len(book)} book rows, {len(market)} market rows")


if __name__ == "__main__":
    main()
