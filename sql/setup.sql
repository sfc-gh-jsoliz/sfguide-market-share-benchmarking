-- 3. Benchmark: share in bps and the year-over-year growth gap ------------------
CREATE OR REPLACE VIEW MARKET_SHARE_BENCHMARK
  COMMENT = 'Processor volume vs market retail sales by category and month: share (bps), YoY growth of each, and the growth gap in percentage points.'
AS
WITH j AS (
  SELECT p.category_code, p.category_name, p.month_end,
         p.processed_volume_usd, m.market_sales_usd, p.txn_count, p.active_merchants
  FROM MARKET_SHARE_PORTFOLIO_MONTHLY p
  JOIN MARKET_SHARE_RETAIL_SALES m USING (category_code, month_end)
)
SELECT category_code, category_name, month_end, processed_volume_usd, market_sales_usd,
       ROUND(processed_volume_usd::FLOAT / NULLIF(market_sales_usd, 0) * 10000, 2) AS share_bps,
       ROUND((processed_volume_usd::FLOAT / NULLIF(LAG(processed_volume_usd, 12) OVER (PARTITION BY category_code ORDER BY month_end), 0) - 1) * 100, 2) AS book_yoy_pct,
       ROUND((market_sales_usd::FLOAT / NULLIF(LAG(market_sales_usd, 12) OVER (PARTITION BY category_code ORDER BY month_end), 0) - 1) * 100, 2) AS market_yoy_pct,
       ROUND(book_yoy_pct - market_yoy_pct, 2) AS growth_gap_pp,
       txn_count, active_merchants
FROM j;

-- One row per vertical: first and latest share (3-month averages, so one noisy
-- month does not flip a status), share change, YoY growth gap and a status.
CREATE OR REPLACE VIEW MARKET_SHARE_VERTICAL_SUMMARY
  COMMENT = 'Per vertical: share at the start and end of the window (3-month averages), change in bps, latest YoY growth gap, status.'
AS
WITH r AS (
  SELECT b.*, ROW_NUMBER() OVER (PARTITION BY category_code ORDER BY month_end) AS n,
         COUNT(*) OVER (PARTITION BY category_code) AS cnt
  FROM MARKET_SHARE_BENCHMARK b
), a AS (
  SELECT category_code, ANY_VALUE(category_name) AS category_name,
         ROUND(AVG(IFF(n <= 3, share_bps, NULL)), 2) AS share_start_bps,
         ROUND(AVG(IFF(n > cnt - 3, share_bps, NULL)), 2) AS share_now_bps,
         MAX(IFF(n = cnt, month_end, NULL)) AS latest_month,
         MAX(IFF(n = cnt, processed_volume_usd, NULL)) AS processed_latest_usd,
         MAX(IFF(n = cnt, market_sales_usd, NULL)) AS market_latest_usd,
         MAX(IFF(n = cnt, share_bps, NULL)) AS share_latest_bps,
         MAX(IFF(n = cnt, book_yoy_pct, NULL)) AS book_yoy_pct,
         MAX(IFF(n = cnt, market_yoy_pct, NULL)) AS market_yoy_pct,
         MAX(IFF(n = cnt, growth_gap_pp, NULL)) AS growth_gap_pp,
         MAX(IFF(n = cnt, active_merchants, NULL)) AS active_merchants
  FROM r GROUP BY category_code
)
SELECT a.*, ROUND(share_now_bps - share_start_bps, 2) AS share_change_bps,
       ROUND((share_now_bps / NULLIF(share_start_bps, 0) - 1) * 100, 2) AS share_change_pct,
       CASE WHEN share_change_pct >= 3 THEN 'Gaining'
            WHEN share_change_pct <= -3 THEN 'Losing'
            ELSE 'Holding' END AS status
FROM a;

