  category_code STRING, month_end DATE, processed_volume_usd NUMBER(18,0), txn_count NUMBER(18,0), active_merchants NUMBER(9,0));
CREATE OR REPLACE TEMP TABLE MARKET_SHARE_MARKET_RAW (
