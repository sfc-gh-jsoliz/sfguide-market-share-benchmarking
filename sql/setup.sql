-- ============================================================================
-- Market Share & Vertical Benchmarking - sql/setup.sql
-- ----------------------------------------------------------------------------
-- Benchmarks a payments processor's (synthetic) processed volume by merchant
-- category against market retail sales by category, as market share in basis
-- points with a year-over-year growth gap.
--
-- Run top to bottom in a Snowsight worksheet as a user who can use ACCOUNTADMIN
-- (only to create the pack role). Everything else runs as MARKET_SHARE_ROLE.
-- About 15 s on an XSMALL warehouse. Re-runnable.
--
-- Creates: role MARKET_SHARE_ROLE, warehouse SNOWPACK_MARKET_SHARE_WH (XSMALL,
-- auto-suspend 60 s), database SNOWPACK_MARKET_SHARE with schema CORE:
--   tables  MARKET_SHARE_MERCHANT_CATEGORY, MARKET_SHARE_PORTFOLIO_MONTHLY,
--           MARKET_SHARE_RETAIL_SALES, MARKET_SHARE_REPORTS
--   views   MARKET_SHARE_BENCHMARK, MARKET_SHARE_VERTICAL_SUMMARY,
--           MARKET_SHARE_DATA_SOURCE_INFO
--   semantic view MARKET_SHARE_SV, Cortex Agent MARKET_SHARE_AGENT,
--   stage APP_STAGE (for the optional Streamlit in Snowflake deploy).
--
-- Both sides are synthetic here (data/generate.py, fixed seed). The optional
-- sql/setup_census.sql swaps the market side for US Census retail sales from a
-- free Marketplace listing. Remove everything with sql/cleanup.sql.
-- ============================================================================

-- 1. Pack role (least privilege) ----------------------------------------------
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS MARKET_SHARE_ROLE
  COMMENT = 'Market Share & Vertical Benchmarking pack role';
SET my_user = CURRENT_USER();
GRANT ROLE MARKET_SHARE_ROLE TO USER IDENTIFIER($my_user);
GRANT CREATE DATABASE ON ACCOUNT TO ROLE MARKET_SHARE_ROLE;
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE MARKET_SHARE_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE MARKET_SHARE_ROLE;

USE ROLE MARKET_SHARE_ROLE;
CREATE WAREHOUSE IF NOT EXISTS SNOWPACK_MARKET_SHARE_WH
  WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE SNOWPACK_MARKET_SHARE_WH;
CREATE DATABASE IF NOT EXISTS SNOWPACK_MARKET_SHARE;
CREATE SCHEMA IF NOT EXISTS SNOWPACK_MARKET_SHARE.CORE
  COMMENT = 'Market Share & Vertical Benchmarking: merchant-category market-share benchmarking';
USE SCHEMA SNOWPACK_MARKET_SHARE.CORE;

-- setup_census.sql turns MARKET_SHARE_RETAIL_SALES into a view; drop it if so.
EXECUTE IMMEDIATE $$ BEGIN DROP VIEW IF EXISTS MARKET_SHARE_RETAIL_SALES; EXCEPTION WHEN OTHER THEN NULL; END; $$;

-- 2. Seeded synthetic data ------------------------------------------------------
